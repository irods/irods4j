    @Test
    void testPamInteractiveAuthentication() throws Exception {
        final String runTest = System.getProperty("irods.test.pam_interactive.enable");
        assumeTrue("1".equals(runTest), "Requires a PAM-enabled iRODS server");

        final IRODSApi.ConnectionOptions connOptions = initConnectionOptionsForTLS();

        // This will hold the session token generated by the server. It will be used later.
        Reference<String> sessionTokenRef = new Reference<>();

        Function<String, String> getInput = prompt -> {
            log.debug("PROMPT (ECHO ON): {}", prompt);
            return "";
        };

        class Counter {
            int count = 0;
        }

        final Counter counter = new Counter();
        Function<String, String> getPassword = prompt -> {
            log.debug("PROMPT (ECHO OFF): {}", prompt);
            if (0 == counter.count++) {
                return password;
            }
            return "otherrods";
        };

        // Authenticate against a multi-prompt system.
        try (IRODSConnection conn = new IRODSConnection(connOptions)) {
            conn.connect(host, port, new QualifiedUsername(username, zone));
            AuthPlugin plugin = new PamInteractiveAuthPlugin(requireSecureConnection, sessionTokenRef, getInput, getPassword);
            conn.authenticate(plugin, new HashMap<>());
            assertFalse(sessionTokenRef.value.isEmpty());
            log.debug("Session token: {}", sessionTokenRef.value);

            // Test the connection.
            assertTrue(IRODSFilesystem.isCollection(conn.getRcComm(), homeCollection));
        }

        // Show the session token can be used for authentication.
        try (IRODSConnection conn = new IRODSConnection(connOptions)) {
            conn.connect(host, port, new QualifiedUsername(username, zone));
            // Passing the session token to the plugin constructor removes the need for
            // the other arguments.
            conn.authenticate(new PamInteractiveAuthPlugin(requireSecureConnection),
                    PamInteractiveAuthPlugin.initAuthArguments(new SessionToken(sessionTokenRef.value)));

            // Test the connection.
            assertTrue(IRODSFilesystem.isCollection(conn.getRcComm(), homeCollection));
        }
    }

    @Test
    void testIncorrectPasswordResultsInError() throws Exception {
        final String runTest = System.getProperty("irods.test.pam_interactive.enable");
        assumeTrue("1".equals(runTest), "Requires a PAM-enabled iRODS server");

        final IRODSApi.ConnectionOptions connOptions = initConnectionOptionsForTLS();

        try (IRODSConnection conn = new IRODSConnection(connOptions)) {
            Function<String, String> getInput = prompt -> {
                log.debug("PROMPT (ECHO ON): {}", prompt);
                return "";
            };

            class Counter {
                int count = 0;
            }

            final Counter counter = new Counter();
            Function<String, String> getPassword = prompt -> {
                log.debug("PROMPT (ECHO OFF): {}", prompt);
                if (0 == counter.count++) {
                    return password;
                }
                return "incorrect_password";
            };

            conn.connect(host, port, new QualifiedUsername(username, zone));
            Reference<String> sessionTokenRef = new Reference<>();
            AuthPlugin plugin = new PamInteractiveAuthPlugin(requireSecureConnection, sessionTokenRef, getInput, getPassword);
            IRODSException e = assertThrows(IRODSException.class, () -> conn.authenticate(plugin, new HashMap<>()));
            assertEquals(IRODSErrorCodes.CAT_INVALID_AUTHENTICATION, e.getErrorCode());
        }
    }

    @Test
    void testIncorrectSessionTokenResultsInError() throws Exception {
        final String runTest = System.getProperty("irods.test.pam_interactive.enable");
        assumeTrue("1".equals(runTest), "Requires a PAM-enabled iRODS server");

        final IRODSApi.ConnectionOptions connOptions = initConnectionOptionsForTLS();

        Function<String, String> getInput = prompt -> {
            log.debug("PROMPT (ECHO ON): {}", prompt);
            return "";
        };

        class Counter {
            int count = 0;
        }

        final Counter counter = new Counter();
        Function<String, String> getPassword = prompt -> {
            log.debug("PROMPT (ECHO OFF): {}", prompt);
            if (0 == counter.count++) {
                return password;
            }
            return "otherrods";
        };

        // Authenticate against a multi-prompt system.
        try (IRODSConnection conn = new IRODSConnection(connOptions)) {
            conn.connect(host, port, new QualifiedUsername(username, zone));

            Reference<String> sessionTokenRef = new Reference<>();
            AuthPlugin plugin = new PamInteractiveAuthPlugin(requireSecureConnection, sessionTokenRef, getInput, getPassword);
            conn.authenticate(plugin, new HashMap<>());
            assertFalse(sessionTokenRef.value.isEmpty());
            log.debug("Session token: {}", sessionTokenRef.value);
        }

        // Show that passing an invalid session token will result in failure.
        try (IRODSConnection conn = new IRODSConnection(connOptions)) {
            conn.connect(host, port, new QualifiedUsername(username, zone));
            IRODSException e = assertThrows(IRODSException.class,
                    () -> conn.authenticate(new PamInteractiveAuthPlugin(requireSecureConnection),
                            PamInteractiveAuthPlugin.initAuthArguments(new SessionToken("invalid-token"))));
            assertEquals(IRODSErrorCodes.CAT_INVALID_AUTHENTICATION, e.getErrorCode());
        }
    }

    /**
     * Returns connection settings that exercise basic support for TLS.
     * DO NOT use this configuration for production purposes.
     */
    static IRODSApi.ConnectionOptions initConnectionOptionsForTLS() {
        IRODSApi.ConnectionOptions options = new IRODSApi.ConnectionOptions();
        options.clientServerNegotiation = "CS_NEG_REQUIRE";
        options.trustManagers = new TrustManager[]{new X509TrustManager() {
            @Override
            public void checkClientTrusted(X509Certificate[] chain, String authType) throws CertificateException {
            }

            @Override
            public void checkServerTrusted(X509Certificate[] chain, String authType) throws CertificateException {
            }

            @Override
            public X509Certificate[] getAcceptedIssuers() {
                return new X509Certificate[0];
            }
        }};
        return options;
    }

